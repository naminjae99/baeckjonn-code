SELECT C.SALES_DATE,C.PRODUCT_ID,C.USER_ID,C.SALES_AMOUNT
FROM (SELECT SALES_DATE,PRODUCT_ID,USER_ID,SALES_AMOUNT
FROM ONLINE_SALE A
WHERE DATE_FORMAT(A.SALES_DATE,'%Y-%m')='2022-03'

UNION

SELECT SALES_DATE,PRODUCT_ID,NULL AS USER_ID,SALES_AMOUNT
FROM OFFLINE_SALE B
WHERE DATE_FORMAT(B.SALES_DATE,'%Y-%m')='2022-03') C 
ORDER BY C.SALES_DATE,C.PRODUCT_ID,C.USER_ID


